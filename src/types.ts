/** Type alias + union type: a book can be in exactly one of two states. */
type BookStatus = "available" | "unavailable";

/** Union type reused by the status filter ("all" means no filtering). */
type StatusFilter = BookStatus | "all";

/** Every button in a book card carries one of these action names. */
type CardAction = "toggle" | "edit" | "delete" | "save" | "cancel";

/** Interface: the shape every book must have. */
interface IBook {
  readonly id: number; // unique identifier
  title: string;
  author: string;
  year: number;
  status: BookStatus;
  genre?: string; // optional property
}

/** Data needed to create a book (id is generated by the library). */
interface NewBookInput {
  title: string;
  author: string;
  year: number;
  genre?: string; // optional
  status?: BookStatus; // optional, defaults to "available"
}

/** Raw text values as they come from form fields. */
interface RawBookInput {
  title: string;
  author: string;
  year: string;
}

/** Fields that can carry a validation message. */
type FieldName = "title" | "author" | "year";
type FieldErrors = Partial<Record<FieldName, string>>;

interface ValidationResult {
  valid: boolean;
  errors: FieldErrors;
  year: number; // parsed year (only meaningful when valid)
}

/** Numbers shown in the statistics bar. */
interface LibraryStats {
  total: number;
  available: number;
  unavailable: number;
}
